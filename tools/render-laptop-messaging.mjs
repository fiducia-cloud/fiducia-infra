#!/usr/bin/env node
// Render one explicit-route NATS/JetStream configuration per laptop cluster.
// Every server lists both peers, client advertisement is disabled, and the
// route plane fails closed on a dedicated mTLS Secret.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { loadTopology } from "./render.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const topologyPath = path.join(root, "laptop", "topology.toml");
export const NATS_CLUSTER_NAME = "fiducia-laptop-production";
export const NATS_ROUTE_PORT = 6222;
export const NATS_SERVER_VERSION = "2.11.17";
export const NATS_SERVER_IMAGE = "nats:2.11.17-alpine@sha256:e4bf19f15fd3218814a4e3c9e0064e1334bd8aa20d5984b9f1a0afd084f8cc00";

function fail(message) {
  throw new Error(message);
}

export function natsServerName(clusterName) {
  return `fiducia-nats-${clusterName}`;
}

export function natsRouteServiceName(clusterName) {
  return `fiducia-nats-route-${clusterName}-tailnet`;
}

export function natsRouteServiceDns(clusterName) {
  return `${natsRouteServiceName(clusterName)}.fiducia.svc.cluster.local`;
}

export function validateMessagingTopology(topology) {
  if (topology.cluster_id !== "fiducia-prod") fail("laptop messaging must retain cluster_id=fiducia-prod");
  if (topology.connectivity !== "wireguard") fail("laptop messaging requires the private WireGuard/Tailscale mesh");
  if (topology.replication_factor !== 3 || topology.cluster.length !== 3) {
    fail("laptop messaging requires exactly three clusters and replication_factor=3");
  }
  const names = topology.cluster.map((cluster) => cluster.name);
  if (new Set(names).size !== 3) fail("laptop messaging cluster names must be unique");
  const sites = topology.cluster.map((cluster) => cluster.site);
  if (sites.some((site) => typeof site !== "string" || !site) || new Set(sites).size !== 3) {
    fail("laptop messaging requires three unique non-empty physical site labels");
  }
  for (const cluster of topology.cluster) {
    if (cluster.platform !== "local-laptop") fail(`${cluster.name} must use platform=local-laptop`);
    if (cluster.storage_class !== "local-path") fail(`${cluster.name} must use local-path storage`);
    if (cluster.node_replicas !== 1) fail(`${cluster.name} must contain one local NATS member`);
  }
  return topology;
}

function renderRoutes(peers) {
  return peers
    .map((peer) => `      nats://${natsRouteServiceDns(peer.name)}:${NATS_ROUTE_PORT}`)
    .join("\n");
}

export function renderNatsConfig(cluster, topology) {
  const peers = topology.cluster.filter((candidate) => candidate.name !== cluster.name);
  if (peers.length !== 2) fail(`${cluster.name} must have exactly two remote messaging peers`);
  return `# GENERATED by tools/render-laptop-messaging.mjs from laptop/topology.toml — do not edit.
# Three independent single-node K3s clusters form one three-server JetStream
# cluster over the private mesh. Client and monitoring planes remain local.
server_name: ${natsServerName(cluster.name)}
server_tags: ["site:${cluster.site}", "cluster:${cluster.name}", "substrate:laptop-k3s"]
port: 4222
http: 8222

max_payload: 8MB
ping_interval: "20s"
write_deadline: "10s"

jetstream {
  store_dir: "/data/jetstream"
  max_memory_store: 512MB
  max_file_store: 8GB
  max_outstanding_catchup: 64MB
  max_buffered_msgs: 10000
  max_buffered_size: 64MB
  request_queue_limit: 5000
  strict: true
  unique_tag: "site"

  limits {
    max_ack_pending: 10000
    duplicate_window: 600s
  }
}

cluster {
  name: ${NATS_CLUSTER_NAME}
  listen: "0.0.0.0:${NATS_ROUTE_PORT}"

  # Other servers must contact this member through the tailnet mirror rather
  # than a pod IP, host IP, or residential address. no_advertise below applies
  # to client URL gossip; it does not remove this route contact address.
  advertise: "${natsRouteServiceDns(cluster.name)}:${NATS_ROUTE_PORT}"
  no_advertise: true
  pool_size: 1

  tls {
    cert_file: "/etc/nats/route-tls/tls.crt"
    key_file: "/etc/nats/route-tls/tls.key"
    ca_file: "/etc/nats/route-tls/ca.crt"
    min_version: "1.3"
    verify: true
    verify_cert_and_check_known_urls: true
    timeout: 5
  }

  routes = [
${renderRoutes(peers)}
  ]
}

# Client accounts and subject permissions remain fail-closed and are delivered
# independently from the route CA/certificate Secret. The include must define a
# SYS system account and a separate JetStream-enabled application account.
include ./auth/auth.conf
`;
}

export function renderLaptopMessaging() {
  const topology = validateMessagingTopology(loadTopology(topologyPath));
  const files = Object.fromEntries(
    topology.cluster.map((cluster) => [
      `laptop/clusters/${cluster.name}/nats.conf`,
      renderNatsConfig(cluster, topology),
    ]),
  );
  return { topology, files };
}

export function syncLaptopMessaging({ check = false } = {}) {
  const { files } = renderLaptopMessaging();
  let drift = 0;
  for (const [relativePath, content] of Object.entries(files)) {
    const absolutePath = path.join(root, relativePath);
    if (check) {
      const current = fs.existsSync(absolutePath) ? fs.readFileSync(absolutePath, "utf8") : null;
      if (current !== content) {
        console.error(`drift: ${relativePath}`);
        drift += 1;
      }
      continue;
    }
    fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
    fs.writeFileSync(absolutePath, content);
    console.log(`wrote ${relativePath}`);
  }
  if (check && drift) fail(`${drift} laptop messaging file(s) stale — run: node tools/render-laptop-messaging.mjs`);
  if (check) console.log("laptop messaging configuration in sync");
}

function main() {
  try {
    syncLaptopMessaging({ check: process.argv.includes("--check") });
  } catch (error) {
    console.error(`error: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) main();
