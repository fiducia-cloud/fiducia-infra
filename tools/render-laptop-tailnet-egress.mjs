#!/usr/bin/env node
// Render the local Tailscale egress Services that preserve Fiducia's peer DNS
// names. Live endpoint observations come from the private tailnet after the
// per-cluster ingress Services are ready.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { loadTopology } from "./render.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const topology = loadTopology(path.join(root, "laptop", "topology.toml"));
const MAX_LIVE_AGE_MS = 10 * 60 * 1000;

const clusterNames = topology.cluster.map((cluster) => cluster.name);

function fail(message) {
  throw new Error(message);
}

function serviceName(kind, clusterName) {
  return `fiducia-${kind}-peer-${clusterName}`;
}

function validateFqdn(value, expectedPrefix, field) {
  if (typeof value !== "string") fail(`${field} must be a full MagicDNS name`);
  const fqdn = value.toLowerCase().replace(/\.$/, "");
  if (fqdn.length > 253 || !fqdn.endsWith(".ts.net")) fail(`${field} must end in .ts.net`);
  if (!fqdn.startsWith(`${expectedPrefix}.`)) fail(`${field} must start with ${expectedPrefix}.`);
  if (!/^[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?$/.test(fqdn)) fail(`${field} is not a valid DNS name`);
  return fqdn;
}

export function validateTailnetObservations(observations, { allowExample = false, now = new Date() } = {}) {
  if (!observations || typeof observations !== "object") fail("observations must be an object");
  if (!["live", "example"].includes(observations.evidenceMode)) fail("evidenceMode must be live or example");
  if (observations.evidenceMode === "example" && !allowExample) {
    fail("example tailnet observations require --allow-example and are not production evidence");
  }
  const observedAt = new Date(observations.observedAt);
  if (Number.isNaN(observedAt.getTime())) fail("observedAt must be an ISO timestamp");
  if (observations.evidenceMode === "live") {
    const age = now.getTime() - observedAt.getTime();
    if (age < -60_000) fail("live observations cannot be materially in the future");
    if (age > MAX_LIVE_AGE_MS) fail("live observations are older than ten minutes");
  }

  const seen = new Set();
  const normalized = {};
  for (const clusterName of clusterNames) {
    const entry = observations.clusters?.[clusterName];
    if (!entry) fail(`missing observations for ${clusterName}`);
    const nodeFqdn = validateFqdn(entry.nodeFqdn, `node-${clusterName}`, `${clusterName}.nodeFqdn`);
    const brainFqdn = validateFqdn(entry.brainFqdn, `brain-${clusterName}`, `${clusterName}.brainFqdn`);
    for (const fqdn of [nodeFqdn, brainFqdn]) {
      if (seen.has(fqdn)) fail(`duplicate tailnet endpoint ${fqdn}`);
      seen.add(fqdn);
      if (observations.evidenceMode === "live" && fqdn.includes(".example.")) {
        fail(`live endpoint cannot use an example domain: ${fqdn}`);
      }
    }
    normalized[clusterName] = { nodeFqdn, brainFqdn };
  }
  return { ...observations, clusters: normalized };
}

function externalNameService({ name, fqdn, port, remoteCluster }) {
  return `apiVersion: v1
kind: Service
metadata:
  name: ${name}
  namespace: fiducia
  labels:
    fiducia.cloud/tailnet-egress: "true"
    fiducia.cloud/remote-cluster: ${remoteCluster}
  annotations:
    tailscale.com/tailnet-fqdn: "${fqdn}"
    tailscale.com/proxy-group: fiducia-egress-proxies
spec:
  type: ExternalName
  externalName: placeholder
  ports:
    - { name: peer, port: ${port}, protocol: TCP }
`;
}

export function renderTailnetEgress(clusterName, observations, options = {}) {
  if (!clusterNames.includes(clusterName)) fail(`unknown laptop cluster ${JSON.stringify(clusterName)}`);
  const evidence = validateTailnetObservations(observations, options);
  const documents = [];

  for (const peerName of clusterNames.filter((candidate) => candidate !== clusterName)) {
    const peer = evidence.clusters[peerName];
    documents.push(externalNameService({
      name: serviceName("node", peerName),
      fqdn: peer.nodeFqdn,
      port: 9090,
      remoteCluster: peerName,
    }));
    documents.push(externalNameService({
      name: serviceName("brain", peerName),
      fqdn: peer.brainFqdn,
      port: 9095,
      remoteCluster: peerName,
    }));
  }

  return `# GENERATED by tools/render-laptop-tailnet-egress.mjs.
# Apply only after the Tailscale operator and remote ingress Services are ready.
${documents.join("---\n")}`;
}

function usage() {
  return [
    "usage: node tools/render-laptop-tailnet-egress.mjs",
    "  --cluster <laptop-*-sim>",
    "  --observations <tailnet-observations.json>",
    "  [--allow-example]",
  ].join("\n");
}

function parseArgs(argv) {
  const args = { cluster: null, observations: null, allowExample: false };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--cluster") args.cluster = argv[++index];
    else if (arg === "--observations") args.observations = argv[++index];
    else if (arg === "--allow-example") args.allowExample = true;
    else if (arg === "--help" || arg === "-h") args.help = true;
    else fail(`unknown argument ${JSON.stringify(arg)}\n${usage()}`);
  }
  return args;
}

function main() {
  try {
    const args = parseArgs(process.argv.slice(2));
    if (args.help) {
      console.log(usage());
      return;
    }
    if (!args.cluster || !args.observations) fail(usage());
    const observations = JSON.parse(fs.readFileSync(path.resolve(args.observations), "utf8"));
    process.stdout.write(renderTailnetEgress(args.cluster, observations, { allowExample: args.allowExample }));
  } catch (error) {
    console.error(`error: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) main();
