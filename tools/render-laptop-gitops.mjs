#!/usr/bin/env node
// Render the cluster-local Argo CD project and root Application for one laptop.
// Production bootstrap is deliberately revision-pinned and manual-sync: a single
// Application contains both stateless and quorum workloads, so unconstrained
// automated self-heal could replace multiple stateful members at once.

import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { loadTopology } from "./render.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const topologyPath = path.join(root, "laptop", "topology.toml");
const repoUrl = "https://github.com/fiducia-cloud/fiducia-infra.git";
const localServer = "https://kubernetes.default.svc";

export function assertCommitRevision(revision) {
  if (typeof revision !== "string" || !/^[0-9a-f]{40}$/i.test(revision)) {
    throw new Error("production GitOps revision must be an exact 40-character Git commit SHA");
  }
  return revision.toLowerCase();
}

export function laptopClusters() {
  const topology = loadTopology(topologyPath);
  return topology.cluster.map((cluster) => cluster.name);
}

export function assertLaptopCluster(cluster) {
  if (!laptopClusters().includes(cluster)) {
    throw new Error(`unknown laptop cluster ${JSON.stringify(cluster)}`);
  }
  return cluster;
}

function projectYaml() {
  return `apiVersion: argoproj.io/v1alpha1
kind: AppProject
metadata:
  name: fiducia-laptop-production
  namespace: argocd
  labels:
    fiducia.cloud/substrate: laptop-k3s
    fiducia.cloud/environment: production
spec:
  description: Revision-pinned, cluster-local Fiducia laptop production applications
  sourceRepos:
    - ${repoUrl}
  destinations:
    - namespace: fiducia
      server: ${localServer}
  orphanedResources:
    warn: true
  clusterResourceWhitelist:
    - group: ""
      kind: Namespace
    - group: rbac.authorization.k8s.io
      kind: ClusterRole
    - group: rbac.authorization.k8s.io
      kind: ClusterRoleBinding
  namespaceResourceWhitelist:
    - { group: "", kind: ConfigMap }
    - { group: "", kind: Service }
    - { group: "", kind: ServiceAccount }
    - { group: apps, kind: Deployment }
    - { group: apps, kind: StatefulSet }
    - { group: apps, kind: DaemonSet }
    - { group: rbac.authorization.k8s.io, kind: Role }
    - { group: rbac.authorization.k8s.io, kind: RoleBinding }
    - { group: networking.k8s.io, kind: NetworkPolicy }
    - { group: policy, kind: PodDisruptionBudget }
`;
}

function applicationYaml(cluster, revision) {
  const appName = `fiducia-${cluster}`;
  return `apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: ${appName}
  namespace: argocd
  labels:
    fiducia.cloud/cluster: ${cluster}
    fiducia.cloud/substrate: laptop-k3s
    fiducia.cloud/environment: production
  annotations:
    fiducia.cloud/governing-issue: DEN-944
spec:
  project: fiducia-laptop-production
  source:
    repoURL: ${repoUrl}
    targetRevision: ${revision}
    path: laptop/clusters/${cluster}
  destination:
    server: ${localServer}
    namespace: fiducia
  revisionHistoryLimit: 10
  syncPolicy:
    # Intentionally no automated block. The root contains StatefulSets and must
    # be promoted one cluster/member at a time through promote-laptop-cluster.sh.
    syncOptions:
      - CreateNamespace=true
      - PruneLast=true
      - ApplyOutOfSyncOnly=true
      - RespectIgnoreDifferences=true
    managedNamespaceMetadata:
      labels:
        fiducia.cloud/cluster: ${cluster}
        fiducia.cloud/substrate: laptop-k3s
        fiducia.cloud/environment: production
`;
}

export function renderLaptopGitOps(cluster, revision) {
  assertLaptopCluster(cluster);
  const pinnedRevision = assertCommitRevision(revision);
  return `# GENERATED by tools/render-laptop-gitops.mjs.
# Cluster-local bootstrap only; do not commit credentials into this bundle.
${projectYaml()}---
${applicationYaml(cluster, pinnedRevision)}`;
}

function usage() {
  return "usage: node tools/render-laptop-gitops.mjs --cluster <laptop-*-sim> --revision <40-char-sha>";
}

function parseArgs(argv) {
  let cluster;
  let revision;
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--cluster") cluster = argv[++index];
    else if (arg === "--revision") revision = argv[++index];
    else if (arg === "--help" || arg === "-h") return { help: true };
    else throw new Error(`unknown argument ${JSON.stringify(arg)}\n${usage()}`);
  }
  if (!cluster || !revision) throw new Error(usage());
  return { cluster, revision, help: false };
}

function main() {
  try {
    const args = parseArgs(process.argv.slice(2));
    if (args.help) {
      console.log(usage());
      return;
    }
    process.stdout.write(renderLaptopGitOps(args.cluster, args.revision));
  } catch (error) {
    console.error(`error: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) main();
